export function classifyWork(pub) {
    const type = pub.type || '';
    const note = pub.note || '';
    const text = `${type} ${note}`.toLowerCase();

    let base = 'zero';
    let baseLabel = 'На второй этаж';
    if (type.includes('металлокаркас') || text.includes('металлокаркас')) {
        base = 'metal';
        baseLabel = 'На металлокаркасе';
    } else if (type.includes('бетон')) {
        base = 'concrete';
        baseLabel = 'На бетоне';
    } else if (type.includes('Перила') || /ограждени|поручн/i.test(note) && !type) {
        base = 'railing';
        baseLabel = 'Ограждение';
    }

    const tags = [];
    if (text.includes('подсвет')) tags.push('led');
    if (text.includes('стекл') || GLASS_IDS.has(pub.id)) tags.push('glass');
    if (text.includes('метал') || METAL_RAIL_IDS.has(pub.id)) tags.push('metal');

    const title = SHORT_TITLES[pub.id]
        || (note ? note.charAt(0).toUpperCase() + note.slice(1) : null)
        || (type === 'Лестница на бетонном основании' ? 'Отделка бетонной лестницы деревом' : null)
        || (type === 'Лестница на металлокаркасе' ? 'Ступени и ограждение на металлокаркас' : null)
        || 'Деревянная лестница на второй этаж';

    const captionParts = [];
    if (pub.material && pub.material !== 'Другое') captionParts.push(pub.material);
    captionParts.push(baseLabel);
    if (note && SHORT_TITLES[pub.id]) captionParts.push(note);

    return {
        ...pub,
        base,
        baseLabel,
        tags,
        displayTitle: title,
        displayCaption: captionParts.join(' · '),
    };
}
